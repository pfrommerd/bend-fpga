// Generates the mechanical parts of isa/lc4/PROOF.bend: one case per
// instruction, with every Word field split into its bits so that decode
// and encode compute on it.
//
//   bun tools/gen/lc4_proofs.ts > isa/lc4/PROOF.gen.bend

const insns: [string, [string, number][]][] = [
  ["BR", [["n", 0], ["z", 0], ["p", 0], ["off", 9]]],
  ["ADD", [["d", 3], ["s", 3], ["t", 3]]],
  ["MUL", [["d", 3], ["s", 3], ["t", 3]]],
  ["SUB", [["d", 3], ["s", 3], ["t", 3]]],
  ["DIV", [["d", 3], ["s", 3], ["t", 3]]],
  ["ADDI", [["d", 3], ["s", 3], ["imm", 5]]],
  ["CMP", [["s", 3], ["t", 3]]],
  ["CMPU", [["s", 3], ["t", 3]]],
  ["CMPI", [["s", 3], ["imm", 7]]],
  ["CMPIU", [["s", 3], ["imm", 7]]],
  ["JSRR", [["s", 3]]],
  ["JSR", [["imm", 11]]],
  ["AND", [["d", 3], ["s", 3], ["t", 3]]],
  ["NOT", [["d", 3], ["s", 3]]],
  ["OR", [["d", 3], ["s", 3], ["t", 3]]],
  ["XOR", [["d", 3], ["s", 3], ["t", 3]]],
  ["ANDI", [["d", 3], ["s", 3], ["imm", 5]]],
  ["LDR", [["d", 3], ["s", 3], ["off", 6]]],
  ["STR", [["t", 3], ["s", 3], ["off", 6]]],
  ["RTI", []],
  ["CONST", [["d", 3], ["imm", 9]]],
  ["SLL", [["d", 3], ["s", 3], ["amt", 4]]],
  ["SRA", [["d", 3], ["s", 3], ["amt", 4]]],
  ["SRL", [["d", 3], ["s", 3], ["amt", 4]]],
  ["MOD", [["d", 3], ["s", 3], ["t", 3]]],
  ["JMPR", [["s", 3]]],
  ["JMP", [["off", 11]]],
  ["HICONST", [["d", 3], ["imm", 8]]],
  ["TRAP", [["vec", 8]]],
];

// a pattern naming every bit of a w-bit field (w = 0: a Bool field)
function pat(name: string, w: number): string {
  if (w === 0) return name;
  let p = "WCon{" + name + (w - 1) + ", WNil{}}";
  for (let k = w - 2; k >= 0; k--) p = "WCon{" + name + k + ", " + p + "}";
  return p;
}

const out: string[] = [];
out.push("# GENERATED by tools/gen/lc4_proofs.ts; do not edit.");
out.push("");
out.push("def decode_encode(i):");
out.push("  match i:");
for (const [k, fs] of insns) {
  out.push(`    case S.${k}{${fs.map(([n, w]) => pat(n, w)).join(", ")}}:`);
  out.push("      {==}");
}
console.log(out.join("\n"));

// priv_unobservable: exec only passes priv through to the next machine
const P = "S.Machine{pc, nzp, priv, regs, mem}";
const P0 = "S.Machine{pc, nzp, False{}, regs, mem}";
const out2: string[] = [];
out2.push("");
out2.push("# the privilege bit only flows into the next privilege bit");
out2.push("def priv.exec(i: S.Insn, -pc: Word(16n), -nzp: Word(3n), -priv: Bool, -regs: M.Mem<16n>, -mem: M.Mem<16n>) ->");
out2.push(`  {S.erase_m(S.step.go(${P}, S.retire.go(Some{i}, pc, nzp, priv, regs, mem)))`);
out2.push(`    == S.erase_m(S.step.go(${P0}, S.retire.go(Some{i}, pc, nzp, False{}, regs, mem))) : Maybe<&2, S.Machine>}:`);
out2.push("  match i:");
for (const [k, fs] of insns) {
  out2.push(`    case S.${k}{${fs.map(([n]) => n).join(", ")}}:`);
  out2.push("      {==}");
}
console.log(out2.join("\n"));
