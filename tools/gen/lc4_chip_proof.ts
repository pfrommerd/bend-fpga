// Generates the proof that a single-cycle LC4 chip implements the spec.
//
//   bun tools/gen/lc4_chip_proof.ts <chip-dir> [<run> <law> <call>]
//
// <run> names the chip's def C.<run>(i, pc, nzp, rf, mem): what the chip
// does with instruction i at the PC (default step_with); <law> the law in
// LAWS.bend (default implements_lc4), and <call> how the law's proof
// starts (default "by_insn(M.get(16n, 16n, pc, mem), pc, nzp, rf, mem)",
// with the law's parameters). The proof generalizes over the instruction word,
// splits it into its 16 bits, and splits on the opcode and sub-opcode bits
// the decoder reads; in each case both sides compute to the same machine.

const dir = process.argv[2] ?? "chips/lc4_single";
const run = process.argv[3] ?? "step_with";
const law = process.argv[4] ?? "implements_lc4";
const params = process.argv[5] ?? "pc, nzp, rf, mem";
const call = process.argv[6] ?? "by_insn(M.get(16n, 16n, pc, mem), pc, nzp, rf, mem)";

const bits = Array.from({ length: 16 }, (_, k) => 15 - k); // b15 .. b0
const insn = bits.slice().reverse().reduceRight((acc, k) => `WCon{b${k}, ${acc}}`, "WNil{}");
const pcw = Array.from({ length: 16 }, (_, k) => k).reduceRight((acc, k) => `WCon{p${k}, ${acc}}`, "WNil{}");

const mach = "S.Machine{pc, nzp, False{}, rf, mem}";
const goal = (i: string) =>
  `{S.erase_m(S.step.go(${mach}, S.retire.go(S.decode(${i}), pc, nzp, False{}, rf, mem)))\n` +
  `    == S.when(S.step.go(${mach}, S.retire.go(S.decode(${i}), pc, nzp, False{}, rf, mem)), C.abs(C.${run}(${i}, pc, nzp, rf, mem))) : Maybe<&2, S.Machine>}`;

// the bits to split under each opcode (b15 b14 b13 b12), in descending order
type Split = string[] | null;
const B = (x: number) => (x ? "True{}" : "False{}");
const splits: Record<string, string[][]> = {
  "0001": [["b5"], ["b4", "b3"]], // ADDI when b5, else ADD/MUL/SUB/DIV by b4 b3
  "0010": [["b8", "b7"]],
  "0100": [["b11"]],
  "0101": [["b5"], ["b4", "b3"]],
  "1010": [["b5", "b4"]],
  "1100": [["b11"]],
};

const out: string[] = [];
const ind = (n: number) => "  ".repeat(n);

// a leaf: both sides compute; JSR (0100 with b11) reads PC[15], so the PC
// is split into bits there
function leaf(depth: number, op: string, path: Record<string, number>) {
  if (op === "0100" && path["b11"] === 1) {
    out.push(`${ind(depth)}match pc:`);
    out.push(`${ind(depth + 1)}case ${pcw}:`);
    out.push(`${ind(depth + 2)}{==}`);
  } else {
    out.push(`${ind(depth)}{==}`);
  }
}

function split(depth: number, op: string, levels: string[][], path: Record<string, number>) {
  if (levels.length === 0) return leaf(depth, op, path);
  const vars = levels[0];
  out.push(`${ind(depth)}match ${vars.join(" ")}:`);
  for (let v = 0; v < 1 << vars.length; v++) {
    const vals = vars.map((_, j) => (v >> (vars.length - 1 - j)) & 1);
    out.push(`${ind(depth + 1)}case ${vals.map(B).join(" ")}:`);
    const p = { ...path };
    vars.forEach((x, j) => (p[x] = vals[j]));
    // ADDI/ANDI (b5 set) need no further split
    if ((op === "0001" || op === "0101") && vars[0] === "b5" && vals[0] === 1) leaf(depth + 2, op, p);
    else split(depth + 2, op, levels.slice(1), p);
  }
}

out.push(`# ${dir}/PROOF.bend: GENERATED by tools/gen/lc4_chip_proof.ts; do not edit.`);
out.push("#");
out.push("# The proof generalizes over the fetched instruction, splits it into its");
out.push("# bits and case-splits on the opcode and sub-opcode bits: in each case the");
out.push("# spec's step and the chip's cycle compute to the same machine.");
out.push("");
out.push("import Base");
out.push("import ../../hdl/mem.bend as M");
out.push("import ../../isa/lc4/spec.bend as S");
out.push("import ./chip.bend as C");
out.push("import ./LAWS.bend as Laws");
out.push("");
out.push("# the step from instruction bits b15 .. b0");
out.push(`def by_bits(${bits.map((k) => `b${k}: Bool`).join(", ")}, +pc: Word(16n), -nzp: Word(3n), -rf: M.Mem<16n>, -mem: M.Mem<16n>) ->`);
out.push(`  ${goal(insn)}:`);
out.push("  match b15 b14 b13 b12:");
for (let o = 0; o < 16; o++) {
  const op = o.toString(2).padStart(4, "0");
  out.push(`    case ${op.split("").map((c) => B(+c)).join(" ")}:`);
  split(3, op, splits[op] ?? [], {});
}
out.push("");
out.push("# the step from any instruction word");
out.push(`def by_insn(i: Word(16n), +pc: Word(16n), -nzp: Word(3n), -rf: M.Mem<16n>, -mem: M.Mem<16n>) ->`);
out.push(`  ${goal("i")}:`);
out.push("  match i:");
out.push(`    case ${insn}:`);
out.push(`      by_bits(${bits.map((k) => `b${k}`).join(", ")}, pc, nzp, rf, mem)`);
out.push("");
out.push(`def Laws.${law}(${params}):`);
out.push(`  ${call}`);
console.log(out.join("\n"));
